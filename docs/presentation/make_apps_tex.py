#!/usr/bin/env python3
"""Generate apps_slides.tex (one Beamer frame per two applications) from apps.json.
Shared source of truth with make_deck.js, so the PowerPoint and the LaTeX deck always list the same 22 apps."""
import json, pathlib, re
HERE = pathlib.Path(__file__).parent
apps = json.loads((HERE / "apps.json").read_text())

def tex(s):
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$")]:
        s = s.replace(a, b)
    s = s.replace("→", r"$\rightarrow$").replace("≤", r"$\le$").replace("2⁶", r"2\textsuperscript{6}")
    s = re.sub(r"uncertain<(\w+)>", r"\\texttt{uncertain<\1>}", s)
    return s

RISK = {"minimal": ("okgreen", "MINIMAL RISK"), "limited": ("gold!85!black", "LIMITED RISK"), "high": ("badred", "HIGH RISK")}

def card(i, a):
    col, label = RISK[a["risk"]]
    items = "\n".join(rf"\item {tex(d)}" for d in a["does"])
    tools = r"\enspace ".join(tex(t) for t in a["tools"])
    progs = f'{a["programs"]} program{"s" if a["programs"] > 1 else ""}'
    return rf"""\begin{{tcolorbox}}[appcard,equal height group=apps{(i+1)//2}]
{{\fontsize{{6.5}}{{8}}\selectfont\color{{muted}}{i:02d}\,/\,22}}\hfill\riskpill{{{col}}}{{{label}}}\\[1pt]
{{\normalsize\bfseries\color{{navy}}{tex(a["name"])}}}\\[-1pt]
{{\scriptsize\bfseries\color{{gold!85!black}}{tex(a["sector"])}}}\par\vspace{{3pt}}
{{\scriptsize\textbf{{\color{{navy}}Challenge}}\enspace {tex(a["challenge"])}\par}}\vspace{{2pt}}
{{\fontsize{{6.5}}{{8}}\selectfont\bfseries\color{{muted}}WHAT IT DOES}}
\begin{{itemize}}\setlength\itemsep{{0pt}}\scriptsize
{items}
\end{{itemize}}
\vspace{{1pt}}\govbox{{{tex(a["governance"])}}}\par\vspace{{3pt}}
{{\fontsize{{6.5}}{{8}}\selectfont\ttfamily\color{{navy2}}{tools}}}\hfill{{\fontsize{{6.5}}{{8}}\selectfont\color{{muted}}{progs}}}
\end{{tcolorbox}}"""

out = ["% Generated by make_apps_tex.py from apps.json: do not edit by hand."]
i = 0
while i < len(apps):
    g = apps[i]["group"]
    pair = [apps[i]] + ([apps[i + 1]] if i + 1 < len(apps) and apps[i + 1]["group"] == g else [])
    dirs = ", ".join(tex(p["dir"]) for p in pair)
    out.append(rf"""
\begin{{frame}}{{Applications · {tex(g)}}}{{enterprise-apps/{dirs}}}
\begin{{columns}}[T,onlytextwidth]
\column{{0.49\textwidth}}
{card(i + 1, pair[0])}
\column{{0.49\textwidth}}
{card(i + 2, pair[1]) if len(pair) > 1 else ""}
\end{{columns}}
\end{{frame}}""")
    i += len(pair)
(HERE / "apps_slides.tex").write_text("\n".join(out) + "\n")
print("wrote", len(out) - 1, "frames")
